"""
Extend the shipped Markdown extension 'wikilinks'
"""
import re
import xml.etree.ElementTree

from django.contrib.sites.models import Site
from django.urls import reverse
from django.utils.text import slugify
from markdown.extensions import Extension
from markdown.extensions import wikilinks
from wiki.conf import settings
from wiki.core.markdown import add_to_registry
from wiki.models import URLPath


def _slug_candidates(label):
    """Yield the slugs a label may refer to, preferred first."""
    # The slug suggested when creating an article with this label as its title
    # (see URLify in wiki/js/urlify.js): lower case, words joined by hyphens.
    slug = slugify(label)[: URLPath.SLUG_MAX_LENGTH]
    if slug:
        yield slug
    # The format previously generated by this extension, so links to articles
    # created with it keep working.
    legacy_slug = re.sub(r"([ ]+_)|(_[ ]+)|([ ]+)", "_", label)
    if legacy_slug != slug:
        yield legacy_slug


def _find_child(parents, slug):
    if settings.URL_CASE_SENSITIVE:
        lookup = {"slug": slug}
    else:
        lookup = {"slug__iexact": slug}
    return URLPath.objects.filter(parent__in=parents, **lookup).first()


def build_url(label, base, end, md):
    """Build a url from the label, a base, and an end."""
    candidates = list(_slug_candidates(label))
    # Nevermind about the base we are fed, just keep the original
    # call pattern from the wikilinks plugin for later...
    base = reverse("wiki:get", kwargs={"path": ""})
    # Prefer a child of the current article, linked relatively...
    urlpaths = md.article.urlpath_set.all()
    for slug in candidates:
        child = _find_child(urlpaths, slug)
        if child:
            return f"{child.slug}{end}"
    # ...then an article at the root of the wiki.
    root = URLPath.objects.root_nodes().filter(site=Site.objects.get_current())
    for slug in candidates:
        child = _find_child(root, slug)
        if child:
            return f"{base}{child.slug}{end}"
    # The article does not exist yet: point at the slug it would be given.
    return f"{base}{candidates[0]}{end}"


class WikiLinkExtension(Extension):
    def __init__(self, **kwargs):
        # set extension defaults
        self.config = {
            "base_url": ["", "String to append to beginning or URL."],
            "end_url": ["/", "String to append to end of URL."],
            "html_class": ["wiki_wikilink", "CSS hook. Leave blank for none."],
            "build_url": [build_url, "Callable formats URL from label."],
        }
        super().__init__(**kwargs)

    def extendMarkdown(self, md):
        self.md = md

        # append to end of inline patterns
        WIKILINK_RE = r"\[\[([\w0-9_ -]+)\]\]"
        wikilinkPattern = WikiLinks(WIKILINK_RE, self.getConfigs())
        wikilinkPattern.md = md

        add_to_registry(
            md.inlinePatterns, "wikilink", wikilinkPattern, "<not_strong"
        )


class WikiLinks(wikilinks.WikiLinksInlineProcessor):
    def handleMatch(self, m, data):
        base_url, end_url, html_class = self._getMeta()
        label = m.group(1).strip()
        url = self.config["build_url"](label, base_url, end_url, self.md)
        # a = markdown.util.etree.Element("a")
        a = xml.etree.ElementTree.Element("a")
        a.text = label
        a.set("href", url)
        if html_class:
            a.set("class", html_class)
        return a, m.start(0), m.end(0)


def makeExtension(*args, **kwargs):
    """Return an instance of the extension."""
    return WikiLinkExtension(*args, **kwargs)
